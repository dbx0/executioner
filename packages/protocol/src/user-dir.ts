import { homedir } from 'node:os'
import { join } from 'node:path'

/**
 * Overrides the user-level Executioner directory. Set it to point a whole
 * install (connections, secrets, skills, saved agents) somewhere else; the test
 * suite sets it so a run never reads or writes the real `~/.executioner`.
 */
export const GLOBAL_DIR_ENV = 'EXECUTIONER_HOME'

/**
 * The user-level directory, `~/.executioner` unless EXECUTIONER_HOME says
 * otherwise. Everything under it is shared by every engagement, which is the
 * point: switching workspaces must not lose your connections or your keys.
 */
export function globalDir(): string {
  const override = process.env[GLOBAL_DIR_ENV]
  return override !== undefined && override.trim() !== '' ? override : join(homedir(), '.executioner')
}

/** Paths inside the user-level directory. Resolved per call so the env override applies. */
export const globalLayout = {
  dir: globalDir,
  /** Connections + secrets, shared across engagements. */
  database: () => join(globalDir(), 'global.sqlite'),
  /** The Agent Skills config (folder + per-agent toggles). */
  skillsConfig: () => join(globalDir(), 'skills.json'),
  /** The project-MCP wiring config (per-agent on/off for MCP injection). */
  agentMcpConfig: () => join(globalDir(), 'agent-mcp.json'),
  /** Keypairs generated by SSH enrollment, so a saved connection keeps working. */
  sshKeys: () => join(globalDir(), 'ssh'),
  /** Saved agents (written by the engine's SavedAgentsStore). */
  agents: () => join(globalDir(), 'agents.json'),
}
